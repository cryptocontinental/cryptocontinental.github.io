function currentLang() {
  const saved = localStorage.getItem("cjw-lang");
  if (saved === "zh" || saved === "en") return saved;
  return "en";
}

function applyLang(lang) {
  const pack = I18N[lang] || I18N.en;
  document.documentElement.lang = pack.dir;
  document.documentElement.setAttribute("data-lang", lang);
  localStorage.setItem("cjw-lang", lang);

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (pack[key] != null) el.textContent = pack[key];
  });
  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (pack[key] != null) el.setAttribute("placeholder", pack[key]);
  });
  document.querySelectorAll("[data-i18n-title]").forEach((el) => {
    const key = el.getAttribute("data-i18n-title");
    if (pack[key] != null) document.title = pack[key];
  });

  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.classList.toggle("active", btn.getAttribute("data-set-lang") === lang);
  });
}

document.addEventListener("DOMContentLoaded", () => {
  applyLang(currentLang());
  document.querySelectorAll("[data-set-lang]").forEach((btn) => {
    btn.addEventListener("click", () => applyLang(btn.getAttribute("data-set-lang")));
  });
});
